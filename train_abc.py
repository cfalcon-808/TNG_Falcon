class EpisodeCounterCallback(BaseCallback):
    def __init__(self):
        super().__init__()
        self.episode_count = 0

    def _on_step(self):
        dones = self.locals.get("dones", None)
        if dones is not None:
            self.episode_count += int(np.sum(dones))
        self.logger.record("1.episode_stats/2.episodes_total_done", float(self.episode_count))
        return True

class WinStatsCallback(BaseCallback):
    """
    Windowed win/timeout stats + optional realized tiger-mode tracking.
    If env includes info["tiger_ai"] at episode end, we will track it.
    """
    def __init__(self, log_every_episodes: int = 200, window_episodes: int = 1_000, verbose: int = 0):
        super().__init__(verbose)
        self.log_every_episodes = log_every_episodes
        self.last_logged_episodes = 0

        # cumulative
        self.episodes = 0
        self.goat_wins = 0
        self.tiger_wins = 0
        self.max_timeouts = 0
        self.repeat_timeouts = 0

        # rolling window of winners
        self.window = deque(maxlen=window_episodes)

        # rolling window of realized opponent modes (optional)
        self.window_tiger_ai = deque(maxlen=window_episodes)  # values: greedy/smart/None
        self.window_goat_ai = deque(maxlen=window_episodes)   # values: random/model/None

    def _on_step(self) -> bool:
        dones = self.locals.get("dones", None)
        infos = self.locals.get("infos", None)

        if dones is not None and infos is not None:
            for done, info in zip(dones, infos):
                if not done:
                    continue

                winner = info.get("winner", None)

                self.episodes += 1
                if winner == "Goat":
                    self.goat_wins += 1
                elif winner == "Tiger":
                    self.tiger_wins += 1
                elif winner == "MaxTimeout":
                    self.max_timeouts += 1
                elif winner == "RepeatTimeout":
                    self.repeat_timeouts += 1

                self.window.append(winner)

                # optional: realized opponent mode
                # env_tng_falcon can set info["tiger_ai"] = TIGER_AI_GREEDY/SMART (or strings)
                self.window_tiger_ai.append(info.get("tiger_ai", None))
                self.window_goat_ai.append(info.get("goat_opponent_ai", info.get("goat_ai", None)))

        # always keep current episode index in logs
        self.logger.record("1.episode_stats/1.episode_index", float(self.episodes))

        if (self.episodes - self.last_logged_episodes) >= self.log_every_episodes and self.episodes > 0:
            total = float(self.episodes)

            self.last_logged_episodes = self.episodes
            # Order of logs (to control TB display grouping)
            self.logger.record("1.episode_stats/3.episodes_total_winstats", total)
            self.logger.record("1.episode_stats/4.goat_win_rate", self.goat_wins / total)
            self.logger.record("1.episode_stats/5.tiger_win_rate", self.tiger_wins / total)
            self.logger.record("1.episode_stats/6.max_timeout_rate", self.max_timeouts / total)
            self.logger.record("1.episode_stats/7.repeat_timeout_rate", self.repeat_timeouts / total)

            w = len(self.window)
            if w > 0:
                goat = sum(1 for x in self.window if x == "Goat") / w
                tiger = sum(1 for x in self.window if x == "Tiger") / w
                to = sum(1 for x in self.window if x == "MaxTimeout") / w
                st = sum(1 for x in self.window if x == "RepeatTimeout") / w

                self.logger.record("2.window_stats/1.episodes_tracked", float(w))
                self.logger.record("2.window_stats/2.goat_win_rate", goat)
                self.logger.record("2.window_stats/3.tiger_win_rate", tiger)
                self.logger.record("2.window_stats/4.max_timeout_rate", to)
                self.logger.record("2.window_stats/5.repeat_timeout_rate", st)

                # optional realized opponent distribution in the last-N window
                smart = 0
                greedy = 0
                for v in self.window_tiger_ai:
                    if v == TIGER_AI_SMART or v == "smart" or v == "SMART":
                        smart += 1
                    elif v == TIGER_AI_GREEDY or v == "greedy" or v == "GREEDY":
                        greedy += 1
                denom = smart + greedy
                if denom > 0:
                    self.logger.record("2.window_stats/6.realized_greedy_tiger_frac", greedy / denom)
                    self.logger.record("2.window_stats/7.realized_smart_tiger_frac", smart / denom)

                model = 0
                random_goat = 0
                for v in self.window_goat_ai:
                    if v == GOAT_AI_MODEL or v == "model" or v == "MODEL":
                        model += 1
                    elif v == GOAT_AI_RANDOM or v == "random" or v == "RANDOM":
                        random_goat += 1
                denom = model + random_goat
                if denom > 0:
                    self.logger.record("2.window_stats/8.realized_random_goat_frac", random_goat / denom)
                    self.logger.record("2.window_stats/9.realized_model_goat_frac", model / denom)

        return True
    

class TigerMixWrapper(Monitor):
    """
    Monitor wrapper that re-samples tiger_ai on every reset using a callable.
    Keeps it top-level (pickle-friendly) and avoids nested class definitions.
    """
    def __init__(self, env, sample_ai_fn):
        super().__init__(env)
        self._sample_ai_fn = sample_ai_fn

    def reset(self, *, seed=None, options=None):
        # Make sure we are modifying the underlying env that actually owns tiger_ai
        ai = self._sample_ai_fn()
        try:
            self.env.tiger_ai = ai
        except Exception:
            pass
        return super().reset(seed=seed, options=options)


class GoatMixWrapper(Monitor):
    """
    Monitor wrapper that re-samples goat_opponent_ai on every reset using a callable.
    Used when the learner is TIGER and we want to mix random/model goats.
    """
    def __init__(self, env, sample_goat_fn):
        super().__init__(env)
        self._sample_goat_fn = sample_goat_fn

    def reset(self, *, seed=None, options=None):
        goat_ai = self._sample_goat_fn()
        # Propagate to underlying env
        try:
            self.env.goat_opponent_ai = goat_ai
        except Exception:
            pass
        return super().reset(seed=seed, options=options)


