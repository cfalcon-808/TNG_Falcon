def run_single_variation(variation_name: str, reward_weights):
    set_random_seed(SEED)

    phases = normalize_phases(reward_weights)

    variation_core = resolve_variation_core(phases)
    variation_log_dir = f"artifacts/logging/train/{ALGO_TAG}/{variation_core}/{SUITE_TAG}"
    variation_model_dir = f"artifacts/models/train/{ALGO_TAG}/{variation_core}/{SUITE_TAG}"
    os.makedirs(variation_log_dir, exist_ok=True)
    os.makedirs(variation_model_dir, exist_ok=True)

    print(f"Starting {NUM_CPU} env workers ({variation_core})...")
    print(f"ENV_VER={ENV_VER}, MODEL_VER={MODEL_VER}, TIMESTEPS={TIMESTEPS}")
    print(f"DEVICE_MODE={DEVICE_MODE}, DEVICE={DEVICE}")
    print("=" * 70)
    print(f"Starting variation: {variation_name}")
    print("=" * 70)

    tb_subdir = f"{ALGO_TAG}_{variation_core}_{variation_name}"

    policy_kwargs = dict(net_arch=[256, 256, 256])

    resume_path = resolve_resume_path(RESUME_MODEL_PATH)
    if RESUME_MODEL_PATH and not resume_path:
        print(f"[{variation_name}] [WARN] RESUME_MODEL_PATH set but no .zip found at: {RESUME_MODEL_PATH}")
    resumed = bool(resume_path)

    model = None
    model_identity = None

    total_goat = total_tiger = total_to = total_st = 0
    total_eps = 0

    for phase_idx, phase in enumerate(phases):
        phase_steps = phase.get("timesteps", TIMESTEPS)
        phase_rewards = phase.get("reward_weights", None)
        phase_opponent = phase.get("opponent_ai", phase.get("tiger_ai", OPPONENT_AI))
        phase_mix = phase.get("mix_prob", MIX_PROB)
        phase_goat_model = phase.get("goat_model_path", GOAT_MODEL_PATH)
        phase_cpr = phase.get("checkpoints_per_run", CHECKPOINTS_PER_RUN)
        phase_save_freq = max((phase_steps // max(phase_cpr, 1)) // NUM_CPU, 1)

        phase_tiger_ai, phase_goat_opp = resolve_opponent_or_exit(LEARNER_ROLE, phase_opponent)
        phase_mix_env = phase_mix

        print(f"Phase {phase_idx}: timesteps={phase_steps}, opponent_ai={phase_opponent}, mix_prob={phase_mix_env}")
        warn_if_missing_goat_model_path(
            phase_goat_opp,
            phase_goat_model,
            context=f"variation={variation_name} phase={phase_idx}",
        )

        env_fns = [
            make_env(
                i,
                seed=SEED,
                reward_weights=phase_rewards,
                tiger_ai=phase_tiger_ai,
                mix_prob=phase_mix_env,
                goat_opponent_ai=phase_goat_opp,
                goat_model_path=phase_goat_model,
            )
            for i in range(NUM_CPU)
        ]
        vec_env = SubprocVecEnv(env_fns)

        win_stats_callback = WinStatsCallback()
        ep_callback = EpisodeCounterCallback()

        chk_callback = CheckpointCallback(
            save_freq=phase_save_freq,
            save_path=variation_model_dir,
            name_prefix=f"cp_{ALGO_TAG}_{variation_core}_{variation_name}",
            save_replay_buffer=True,
            save_vecnormalize=True,
        )

        callback = CallbackList([
            chk_callback, 
            ep_callback, 
            win_stats_callback
            ]
        )

        phase_tb = f"{tb_subdir}_p{phase_idx}"
        log_path = os.path.join(variation_log_dir, phase_tb)

        if model is None:
            if resume_path:
                print(f"[{variation_name}] Loading existing model for continued training:\n  {resume_path}")
                model = MaskablePPO.load(resume_path, env=vec_env, device=DEVICE)
                model.set_env(vec_env)
                model.verbose = 1
                model.set_logger(configure(log_path, ["tensorboard", "stdout"]))
            else:
                model = MaskablePPO(
                    "MlpPolicy",
                    vec_env,
                    verbose=1,
                    n_steps=N_STEPS,
                    batch_size=BATCH_SIZE,
                    n_epochs=N_EPOCHS,
                    gamma=GAMMA,
                    learning_rate=LEARNING_RATE,
                    ent_coef=ENT_COEF,
                    device=DEVICE,
                    seed=SEED,
                    policy_kwargs=policy_kwargs,
                )
                # KEY FIX: configure logger immediately
                model.set_logger(configure(log_path, ["tensorboard", "stdout"]))
            model_identity = id(model)
            print(f"[{variation_name}] Phase {phase_idx}: initialized model (id={model_identity})")
        else:
            if model_identity is None:
                model_identity = id(model)
            elif id(model) != model_identity:
                raise RuntimeError(
                    f"[{variation_name}] Model instance changed across phases "
                    f"(expected id={model_identity}, got id={id(model)})."
                )
            print(f"[{variation_name}] Phase {phase_idx}: continuing same model (id={model_identity})")
            model.set_env(vec_env)
            model.set_logger(configure(log_path, ["tensorboard", "stdout"]))

        cont = resumed or phase_idx > 0

        # log matchup info AFTER logger exists
        log_matchup_info(model, LEARNER_ROLE, phase_tiger_ai, phase_goat_opp, phase_mix_env)


        model.learn(
            total_timesteps=phase_steps,
            callback=callback,
            progress_bar=True,
            reset_num_timesteps=not cont,
        )

        total_eps += win_stats_callback.episodes
        total_goat += win_stats_callback.goat_wins
        total_tiger += win_stats_callback.tiger_wins
        total_to += win_stats_callback.max_timeouts
        total_st += win_stats_callback.repeat_timeouts

        vec_env.close()

    if total_eps > 0:
        goat = total_goat / float(total_eps)
        tiger = total_tiger / float(total_eps)
        mto = total_to / float(total_eps)
        rto = total_st / float(total_eps)
    else:
        goat = tiger = mto = rto = 0.0

    print(f"[{variation_name}] Summary:")
    print(f"  Goat {goat:.3f} | Tiger {tiger:.3f} | MaxTO {mto:.3f} | RepeatTO {rto:.3f}")

    # Save final model with phase suffix similar to TB naming
    final_name = f"{ALGO_TAG}_{variation_core}_{variation_name}_p{len(phases)-1}"
    final_path = unique_filename(variation_model_dir, final_name)

    model.save(final_path)
    print(f"Saved final model: {final_path}")

    return {
        "variation": variation_name,
        "episodes": total_eps,
        "goat": goat,
        "tiger": tiger,
        "max_timeout": mto,
        "repeat_stall": rto,
        "final_path": final_path,
    }

