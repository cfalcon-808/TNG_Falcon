@dataclass(frozen=True)
class PhaseConfig:
    timesteps: int
    opponent_ai: str
    mix_prob: float | None
    checkpoints_per_run: int
    goat_model_path: str | None
    knobs: dict[str, Any]


def default_phase_config() -> PhaseConfig:
    return PhaseConfig(
        timesteps=TIMESTEPS,
        opponent_ai=OPPONENT_AI,
        mix_prob=MIX_PROB,
        checkpoints_per_run=CHECKPOINTS_PER_RUN,
        goat_model_path=GOAT_MODEL_PATH,
        knobs={},
    )


def _raise_legacy_variation_key_error(key: str, context: str) -> None:
    if key == "tiger_ai":
        raise ValueError(
            f"{context}: 'tiger_ai' is no longer supported. Use 'opponent_ai' instead."
        )
    if key == "reward_weights":
        raise ValueError(
            f"{context}: nested 'reward_weights' is no longer supported. "
            "Put each tuning knob directly in the variation or phase dict."
        )


def normalize_phase_dict(phase_config: dict[str, Any], context: str) -> PhaseConfig:
    if not isinstance(phase_config, dict):
        raise TypeError(f"{context}: expected a dict, got {type(phase_config).__name__}.")

    for legacy_key in LEGACY_VARIATION_KEYS:
        if legacy_key in phase_config:
            _raise_legacy_variation_key_error(legacy_key, context)

    default_phase = default_phase_config()
    knobs = {
        key: value
        for key, value in phase_config.items()
        if key not in CONTROL_KEYS
    }

    return PhaseConfig(
        timesteps=phase_config.get("timesteps", default_phase.timesteps),
        opponent_ai=phase_config.get("opponent_ai", default_phase.opponent_ai),
        mix_prob=phase_config.get("mix_prob", default_phase.mix_prob),
        checkpoints_per_run=phase_config.get("checkpoints_per_run", default_phase.checkpoints_per_run),
        goat_model_path=phase_config.get("goat_model_path", default_phase.goat_model_path),
        knobs=knobs,
    )


def normalize_variation_config(variation_config: Any) -> list[PhaseConfig]:
    if variation_config is None:
        return [default_phase_config()]
    if isinstance(variation_config, dict):
        return [normalize_phase_dict(variation_config, context="variation")]
    if isinstance(variation_config, list):
        return [
            normalize_phase_dict(phase_config, context=f"phase[{idx}]")
            for idx, phase_config in enumerate(variation_config)
        ]
    raise TypeError("Variation config must be None, a dict, or a list of dict phases.")

def core_tag(
    learner_role: str,
    opponent_ai: str,
    mix: bool = False,
    goat_opponent_ai: str | None = None,
) -> str:
    """
    Build a matchup tag:
      - GOAT learner: opponent_ai refers to tiger mode (greedy/smart), mix uses generic MixT.
      - TIGER learner: opponent_ai/goat_opponent_ai refers to goat type (random/model),
        mix marks a mixed-goat opponent.
    """
    learner = "G" if learner_role == GOAT_LEARNER else "T"
    if learner == "T":
        goat_ai = goat_opponent_ai or opponent_ai
        if mix:
            opp = "MixG"
        else:
            opp = "MG" if goat_ai == GOAT_AI_MODEL else "RG"
    else:
        base_opp = "NT" if opponent_ai == TIGER_AI_GREEDY else "ST"
        opp = "MixT" if mix else base_opp
    return f"{learner}v{opp}"


def resolve_opponent_or_exit(learner_role: str, opponent_ai: str) -> tuple[str, str]:
    """
    Map a unified opponent string to (tiger_ai_mode, goat_opponent_ai),
    exiting if the combination is invalid for the current learner role.
    """
    lr = learner_role.lower()
    opp = opponent_ai.lower()

    if lr == GOAT_LEARNER:
        if opp == OPP_TIGER_GREEDY:
            return TIGER_AI_GREEDY, GOAT_AI_RANDOM
        if opp == OPP_TIGER_SMART:
            return TIGER_AI_SMART, GOAT_AI_RANDOM
        print("GOAT learner requires OPPONENT_AI in {tiger_greedy, tiger_smart}")
        sys.exit(1)

    if lr == TIGER_LEARNER:
        if opp == OPP_GOAT_RANDOM:
            return TIGER_AI_SMART, GOAT_AI_RANDOM
        if opp == OPP_GOAT_MODEL:
            return TIGER_AI_SMART, GOAT_AI_MODEL
        print("TIGER learner requires OPPONENT_AI in {goat_random, goat_model}")
        sys.exit(1)

    print("learner_role must be GOAT_LEARNER or TIGER_LEARNER")
    sys.exit(1)


def resolve_variation_core(phases: list[PhaseConfig]) -> str:
    phase_list = phases if phases else [default_phase_config()]
    is_mixed = any(phase.mix_prob is not None for phase in phase_list)

    tiger_modes = set()
    goat_modes = set()
    for phase in phase_list:
        resolved_tiger_ai, resolved_goat_ai = resolve_opponent_or_exit(LEARNER_ROLE, phase.opponent_ai)
        tiger_modes.add(resolved_tiger_ai)
        goat_modes.add(resolved_goat_ai)

    if LEARNER_ROLE == GOAT_LEARNER:
        if is_mixed:
            sample_tiger = next(iter(tiger_modes), TIGER_AI_GREEDY)
            return core_tag(LEARNER_ROLE, sample_tiger, mix=True, goat_opponent_ai=GOAT_AI_RANDOM)
        if len(tiger_modes) == 1:
            only_tiger = next(iter(tiger_modes))
            return core_tag(LEARNER_ROLE, only_tiger, mix=False, goat_opponent_ai=GOAT_AI_RANDOM)
        return "GvNTST"

    if is_mixed:
        sample_goat = next(iter(goat_modes), GOAT_AI_RANDOM)
        return core_tag(LEARNER_ROLE, TIGER_AI_SMART, mix=True, goat_opponent_ai=sample_goat)
    if len(goat_modes) == 1:
        only_goat = next(iter(goat_modes))
        return core_tag(LEARNER_ROLE, TIGER_AI_SMART, mix=False, goat_opponent_ai=only_goat)
    return "TvRGMG"


def make_goat_model_predict_fn(model_path: str | None):
    if not model_path:
        return None

    model = None

    def _predict(obs, mask):
        nonlocal model
        if model is None:
            model = MaskablePPO.load(model_path, device=DEVICE)
        obs_arr = np.asarray(obs)
        if obs_arr.ndim == 1:
            obs_arr = obs_arr.reshape(1, -1)
        mask_arr = None
        if mask is not None:
            mask_arr = np.asarray(mask, dtype=bool)
            if mask_arr.ndim == 1:
                mask_arr = mask_arr.reshape(1, -1)
        action, _ = model.predict(obs_arr, deterministic=True, action_masks=mask_arr)
        if isinstance(action, np.ndarray):
            return int(action[0])
        return int(action)

    return _predict


def warn_if_missing_goat_model_path(goat_opponent_ai: str, model_path: str | None, context: str):
    if goat_opponent_ai == GOAT_AI_MODEL and not model_path:
        print(f"[WARN] {context}: opponent_ai=goat_model but goat_model_path is not set; falling back to random goat.")


