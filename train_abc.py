def log_matchup_info(model_obj, learner_role, tiger_ai, resolved_goat_ai, mix_prob):
    learner_id = 0.0 if learner_role == GOAT_LEARNER else 1.0
    opp_source_id = 0.0 if learner_role == GOAT_LEARNER else 1.0  # 0=tiger, 1=goat
    if learner_role == GOAT_LEARNER:
        opp_family_id = 1.0 if tiger_ai == TIGER_AI_SMART else 0.0
    else:
        opp_family_id = 1.0 if resolved_goat_ai == GOAT_AI_MODEL else 0.0

    model_obj.logger.record("3.matchup_info/1.learner_id", learner_id)
    model_obj.logger.record("3.matchup_info/2.opp_source_id", opp_source_id)
    model_obj.logger.record("3.matchup_info/3.opp_family_id", opp_family_id)
    model_obj.logger.record("3.matchup_info/4.is_mixed", 0.0 if mix_prob is None else 1.0)
    if mix_prob is not None:
        model_obj.logger.record("3.matchup_info/5.mix_prob", float(mix_prob))
    model_obj.logger.dump(step=model_obj.num_timesteps)


def configure_model_for_phase(
    model: MaskablePPO | None,
    model_identity: int | None,
    vec_env: SubprocVecEnv,
    log_path: str,
    resume_path: str | None,
    variation_name: str,
    phase_idx: int,
    policy_kwargs: dict[str, Any],
) -> tuple[MaskablePPO, int]:
    if model is None:
        if resume_path:
            print(f"[{variation_name}] Loading existing model for continued training:\n  {resume_path}")
            model = MaskablePPO.load(resume_path, env=vec_env, device=DEVICE)
            model.set_env(vec_env)
            model.verbose = 1
        else:
            model = MaskablePPO(
                "MlpPolicy",
                vec_env,
                verbose=1,
                n_steps=N_STEPS,
                batch_size=BATCH_SIZE,
                n_epochs=N_EPOCHS,
                gamma=GAMMA,
                learning_rate=LEARNING_RATE,
                ent_coef=ENT_COEF,
                device=DEVICE,
                seed=SEED,
                policy_kwargs=policy_kwargs,
            )
        model.set_logger(configure(log_path, ["tensorboard", "stdout"]))
        model_identity = id(model)
        print(f"[{variation_name}] Phase {phase_idx}: initialized model (id={model_identity})")
        return model, model_identity

    if model_identity is None:
        model_identity = id(model)
    elif id(model) != model_identity:
        raise RuntimeError(
            f"[{variation_name}] Model instance changed across phases "
            f"(expected id={model_identity}, got id={id(model)})."
        )

    print(f"[{variation_name}] Phase {phase_idx}: continuing same model (id={model_identity})")
    model.set_env(vec_env)
    model.set_logger(configure(log_path, ["tensorboard", "stdout"]))
    return model, model_identity

