# ============================================================
#  Project    : Tigers & Goats – Falcon Branch
#  Module     : Experiment Sweep Runner
#  File       : train_abc.py
#  Version    : mppo_train3.1
#
#  What this file does:
#    Runs an *experiment suite* made of multiple *variations*, where each
#    variation can be either:
#      (A) A single default run (None)
#      (B) A single-phase flat dict (control keys + direct tuning knobs)
#      (C) A multi-phase curriculum (list of flat dict phases) that continues training
#          the *same* model across phases (new TB subdir per phase).
#
#    Each phase creates a fresh SubprocVecEnv, trains for phase_steps, logs
#    windowed outcome metrics, saves periodic checkpoints, then closes the env.
#
#  Key concepts:
#    • EXPERIMENT_NAME / SUITE_TAG:
#         Suite name. Logs + models are grouped under this.
#
#    • CORE (matchup tag):
#         Generated by core_tag(learner_role, opponent_ai, mix=...)
#           - GvNT: Goat vs Normal/Greedy Tiger
#           - GvST: Goat vs Smart Tiger
#           - GvMixT: Goat vs Mixed Tiger (per-reset sampling)
#           - Tv...: Tiger-learner versions (goats become scripted opponent)
#
#    • VARIATIONS:
#         variation_name -> config, where config can be:
#           (A) None
#               → env defaults
#           (B) dict
#               → one phase; supports optional inline keys:
#                   {"timesteps", "opponent_ai", "mix_prob", "checkpoints_per_run", ...knobs...}
#           (C) list[dict]
#               → multi-phase curriculum:
#                   [{"timesteps": ..., "opponent_ai": ..., "mix_prob": ..., ...knobs...}, ...]
#
#    • Tiger mixing (per-reset opponent sampling):
#         If mix_prob is set in a phase, each episode reset samples:
#            TIGER_AI_SMART with probability mix_prob
#            TIGER_AI_GREEDY otherwise
#         Implemented via TigerMixWrapper (Monitor subclass) so it remains
#         pickle-friendly under SubprocVecEnv.
#
#    • Action masking (MaskablePPO requirement):
#         Each worker env is wrapped:
#           BaseEnv -> (Monitor or TigerMixWrapper) -> ActionMasker
#         so MaskablePPO only samples legal actions.
#
#  Outputs (where stuff goes):
#    • Run artifacts (experiment-first):
#         artifacts/{EXPERIMENT_NAME}/
#           ├── meta/         (config_<variation>_<runstamp>.json, git_commit_<variation>_<runstamp>.txt, notes_<variation>_<runstamp>.txt)
#           ├── tb/           (TensorBoard logs by phase)
#           ├── checkpoints/  (phase subfolders with periodic checkpoints)
#           ├── models/       (final_<variation>_<runstamp>_phase_XX.zip + best_<variation>_<runstamp>.zip)
#           ├── eval/
#           └── logs/
#
#    • Resume support:
#         RESUME_MODEL_PATH can be a .zip file OR a directory.
#         If directory, the most recently created .zip is loaded and training
#         continues from it (phase 0 treated as "continued").
#
#  Metrics you should expect in TensorBoard:
#    • 1.episode_stats/*
#         - episode_index
#         - episodes_total_done
#         - overall goat/tiger/timeout/stall rates (cumulative)
#
#    • 2.window_stats/*
#         - windowed goat/tiger/timeout/stall rates over last N episodes
#         - realized opponent fraction (greedy vs smart) in the last N episodes
#           when tiger mode is mixed
#
#    • 3.matchup_info/*
#         - learner_id (0=goat, 1=tiger)
#         - opp_source_id (0=tiger, 1=goat)
#         - opp_family_id (0=greedy/random, 1=smart/model)
#         - is_mixed (0/1)
#         - mix_prob (if mixed)
#
#  Quick Use:
#    1) Choose opponent + role:
#         OPPONENT_AI   = OPP_TIGER_GREEDY
#         # or
#         OPPONENT_AI   = OPP_TIGER_SMART
#         LEARNER_ROLE  = GOAT_LEARNER      # or TIGER_LEARNER
#
#    2) Set identity + compute:
#         EXPERIMENT_NAME = "RobustGoatTraining"
#         TIMESTEPS       = 60_000_000
#         NUM_CPU         = 16
#         DEVICE_MODE     = "gpu"  # uses cuda + larger batch/n_steps
#
#    3) Define variations:
#         VARIATIONS = {
#             "defaultSettings": None,
#             "no_bubble": {"REWARD_BUBBLE_SPACE": 0.0},
#             "no_block": {"REWARD_BLOCK_TIGER": 0.0},
#             "weaker_capture_bias": {"BASE_TIGER_CAPTURE_BIAS": 0.8},
#         }
#
#       Curriculum + mixing example:
#         VARIATIONS = {
#           "greedy_to_smart_mix": [
#             {"timesteps": 10_000_000, "opponent_ai": OPP_TIGER_GREEDY},
#             {"timesteps": 10_000_000, "opponent_ai": OPP_TIGER_SMART},
#             {"timesteps": 30_000_000, "opponent_ai": OPP_TIGER_SMART, "mix_prob": 0.3},
#             {"timesteps": 30_000_000, "opponent_ai": OPP_TIGER_SMART, "mix_prob": 0.5},
#           ]
#         }
#
#    4) Run:
#         python train_abc.py
#
#    5) Watch training:
#         tensorboard --logdir artifacts --port 6006
#
#  Workflow (recommended for ablation studies):
#    1) Establish baseline (single variation, defaults).
#    2) One-at-a-time ablations (set one reward knob to 0.0).
#    3) Group ablations (remove shaping families).
#    4) Magnitude sweeps on selected reward knobs (0.0, 0.25, 0.5, 1.0, 2.0).
#    5) Curriculum runs (greedy -> smart, optional mixing for robustness).
#    6) Evaluate winners with eval_falcon.py across fixed episode counts.
#
