def core_tag(
    learner_role: str,
    opponent_ai: str,
    mix: bool = False,
    goat_opponent_ai: str | None = None,
) -> str:
    """
    Build a matchup tag:
      - GOAT learner: opponent_ai refers to tiger mode (greedy/smart), mix uses generic MixT.
      - TIGER learner: opponent_ai/goat_opponent_ai refers to goat type (random/model),
        mix marks a mixed-goat opponent.
    """
    learner = "G" if learner_role == GOAT_LEARNER else "T"
    if learner == "T":
        goat_ai = goat_opponent_ai or opponent_ai
        if mix:
            opp = "MixG"
        else:
            opp = "MG" if goat_ai == GOAT_AI_MODEL else "RG"
    else:
        base_opp = "NT" if opponent_ai == TIGER_AI_GREEDY else "ST"
        opp = "MixT" if mix else base_opp
    return f"{learner}v{opp}"


def resolve_opponent_or_exit(learner_role: str, opponent_ai: str) -> tuple[str, str]:
    """
    Map a unified opponent string to (tiger_ai_mode, goat_opponent_ai),
    exiting if the combination is invalid for the current learner role.
    """
    lr = learner_role.lower()
    opp = opponent_ai.lower()

    if lr == GOAT_LEARNER:
        if opp == OPP_TIGER_GREEDY:
            return TIGER_AI_GREEDY, GOAT_AI_RANDOM
        if opp == OPP_TIGER_SMART:
            return TIGER_AI_SMART, GOAT_AI_RANDOM
        print("GOAT learner requires OPPONENT_AI in {tiger_greedy, tiger_smart}")
        sys.exit(1)

    if lr == TIGER_LEARNER:
        if opp == OPP_GOAT_RANDOM:
            return TIGER_AI_SMART, GOAT_AI_RANDOM
        if opp == OPP_GOAT_MODEL:
            return TIGER_AI_SMART, GOAT_AI_MODEL
        print("TIGER learner requires OPPONENT_AI in {goat_random, goat_model}")
        sys.exit(1)

    print("learner_role must be GOAT_LEARNER or TIGER_LEARNER")
    sys.exit(1)


def normalize_phases(reward_weights) -> list[dict]:
    if isinstance(reward_weights, list):
        return reward_weights
    if isinstance(reward_weights, dict):
        # Single-phase dict: allow inline timesteps/opponent_ai/mix_prob/checkpoints_per_run
        phase_timesteps = reward_weights.get("timesteps", TIMESTEPS)
        phase_checkpoints = reward_weights.get("checkpoints_per_run", CHECKPOINTS_PER_RUN)
        phase_opponent = reward_weights.get("opponent_ai", reward_weights.get("tiger_ai", OPPONENT_AI))
        phase_mix = reward_weights.get("mix_prob", MIX_PROB)
        phase_goat_model = reward_weights.get("goat_model_path", GOAT_MODEL_PATH)
        phase_rewards = {
            k: v for k, v in reward_weights.items()
            if k not in {"timesteps", "tiger_ai", "opponent_ai", "mix_prob", "checkpoints_per_run", "goat_model_path"}
        } or None
        return [{
            "timesteps": phase_timesteps,
            "opponent_ai": phase_opponent,
            "mix_prob": phase_mix,
            "goat_model_path": phase_goat_model,
            "checkpoints_per_run": phase_checkpoints,
            "reward_weights": phase_rewards,
        }]
    return [{
        "timesteps": TIMESTEPS,
        "opponent_ai": OPPONENT_AI,
        "mix_prob": MIX_PROB,
        "goat_model_path": GOAT_MODEL_PATH,
        "reward_weights": reward_weights,
        "checkpoints_per_run": CHECKPOINTS_PER_RUN,
    }]


def resolve_variation_core(phases: list[dict]) -> str:
    phase_list = phases if phases else [{"opponent_ai": OPPONENT_AI, "mix_prob": MIX_PROB}]
    is_mixed = any(phase.get("mix_prob", MIX_PROB) is not None for phase in phase_list)

    tiger_modes = set()
    goat_modes = set()
    for phase in phase_list:
        phase_opponent = phase.get("opponent_ai", phase.get("tiger_ai", OPPONENT_AI))
        tiger_ai, goat_opp = resolve_opponent_or_exit(LEARNER_ROLE, phase_opponent)
        tiger_modes.add(tiger_ai)
        goat_modes.add(goat_opp)

    if LEARNER_ROLE == GOAT_LEARNER:
        if is_mixed:
            sample_tiger = next(iter(tiger_modes), TIGER_AI_GREEDY)
            return core_tag(LEARNER_ROLE, sample_tiger, mix=True, goat_opponent_ai=GOAT_AI_RANDOM)
        if len(tiger_modes) == 1:
            only_tiger = next(iter(tiger_modes))
            return core_tag(LEARNER_ROLE, only_tiger, mix=False, goat_opponent_ai=GOAT_AI_RANDOM)
        return "GvNTST"

    if is_mixed:
        sample_goat = next(iter(goat_modes), GOAT_AI_RANDOM)
        return core_tag(LEARNER_ROLE, TIGER_AI_SMART, mix=True, goat_opponent_ai=sample_goat)
    if len(goat_modes) == 1:
        only_goat = next(iter(goat_modes))
        return core_tag(LEARNER_ROLE, TIGER_AI_SMART, mix=False, goat_opponent_ai=only_goat)
    return "TvRGMG"


def make_goat_model_predict_fn(model_path: str | None):
    if not model_path:
        return None

    model = None

    def _predict(obs, mask):
        nonlocal model
        if model is None:
            model = MaskablePPO.load(model_path, device=DEVICE)
        obs_arr = np.asarray(obs)
        if obs_arr.ndim == 1:
            obs_arr = obs_arr.reshape(1, -1)
        mask_arr = None
        if mask is not None:
            mask_arr = np.asarray(mask, dtype=bool)
            if mask_arr.ndim == 1:
                mask_arr = mask_arr.reshape(1, -1)
        action, _ = model.predict(obs_arr, deterministic=True, action_masks=mask_arr)
        if isinstance(action, np.ndarray):
            return int(action[0])
        return int(action)

    return _predict


