def make_env(
    rank: int,
    seed: int,
    reward_weights,
    tiger_ai=None,
    mix_prob=None,
    goat_opponent_ai=None,
    goat_model_path=None,
):
    def _init():
        def _sample_ai():
            if mix_prob is None:
                return tiger_ai if tiger_ai is not None else TIGER_AI_MODE
            p = min(max(float(mix_prob), 0.0), 1.0)
            return TIGER_AI_SMART if random.random() < p else TIGER_AI_GREEDY

        def _sample_goat_ai():
            base_goat = goat_opponent_ai if goat_opponent_ai is not None else GOAT_OPPONENT_AI
            if mix_prob is None or LEARNER_ROLE == GOAT_LEARNER:
                return base_goat
            p = min(max(float(mix_prob), 0.0), 1.0)
            return GOAT_AI_MODEL if random.random() < p else GOAT_AI_RANDOM

        goat_model_predict_fn = make_goat_model_predict_fn(goat_model_path)
        base_env = BaseEnv(
            reward_weights=reward_weights,
            tiger_ai=_sample_ai(),
            learner_role=LEARNER_ROLE,
            goat_opponent_ai=_sample_goat_ai(),
            goat_model_predict_fn=goat_model_predict_fn,
        )

        # If mixing, resample per reset
        if mix_prob is not None and LEARNER_ROLE == GOAT_LEARNER:
            env = TigerMixWrapper(base_env, _sample_ai)
        elif mix_prob is not None and LEARNER_ROLE == TIGER_LEARNER:
            env = GoatMixWrapper(base_env, _sample_goat_ai)
        else:
            env = Monitor(base_env)

        env = ActionMasker(env, mask_fn)
        env.reset(seed=seed + rank)
        return env
    return _init

